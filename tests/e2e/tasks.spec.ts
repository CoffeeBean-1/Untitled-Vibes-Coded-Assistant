import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('full task workspace shares records, supports search, lifecycle and undo', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Tasks', exact: true }).click();
  await page.getByRole('button', { name: 'New task', exact: true }).click();
  const editor = page.getByRole('dialog');
  await editor.getByLabel('Task title').fill('Prepare investment review');
  await editor.getByLabel('Description').fill('Summarize manager updates and open questions.');
  await editor.getByLabel('Project or list').fill('Research');
  await editor.getByLabel('Tags').fill('planning, review');
  await editor.getByLabel('Due date', { exact: true }).fill('2026-10-27');
  await editor.getByLabel('Start date', { exact: true }).fill('2026-10-26');
  await editor.getByRole('button', { name: 'Add task', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await page.getByLabel('Search tasks').fill('manager updates');
  const title = page.getByRole('button', { name: 'Prepare investment review', exact: true });
  await expect(title).toBeVisible();
  await expect(page.locator('.task-row')).toHaveCount(1);
  await page.getByRole('button', { name: 'Archive Prepare investment review', exact: true }).click();
  await expect(title).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(title).toBeVisible();
  await page.getByRole('button', { name: 'Move Prepare investment review to trash', exact: true }).click();
  await page.getByRole('button', { name: 'Trash', exact: true }).click();
  await expect(title).toBeVisible();
  await page.getByRole('button', { name: 'Restore Prepare investment review', exact: true }).click();
  await expect(title).toHaveCount(0);
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
  await expect(title).toBeVisible();
  await page.reload();
  await expect(title).toBeVisible();
});

test('backup download, reviewed replacement and recovery preserve the previous workspace', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('checkbox', { name: 'I have reviewed the task content for export' }).check();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download backup', exact: true }).click();
  const download = await downloadPromise; const content = await readFile((await download.path())!, 'utf-8');
  const bundle = JSON.parse(content);
  expect(bundle.tasks).toHaveLength(3); expect(bundle).not.toHaveProperty('anchor');
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
  await page.getByLabel('Task title').fill('Created after backup');
  await page.getByRole('button', { name: 'Add task', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Created after backup', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Choose backup file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(content) });
  const preview = page.getByRole('dialog');
  await expect(preview.getByRole('heading', { name: 'Review backup' })).toBeVisible();
  await preview.getByLabel('Restore mode').selectOption('replace');
  await preview.getByRole('checkbox', { name: 'I have reviewed these changes' }).check();
  await preview.getByRole('button', { name: 'Restore backup', exact: true }).click();
  await expect(preview).toHaveCount(0);
  await expect(page.getByText('Backup restored. Imported reminders remain off. A recovery snapshot is available below.')).toBeVisible();
  await page.getByRole('button', { name: /^Review recovery/ }).first().click();
  await page.getByRole('dialog').getByRole('button', { name: 'Recover workspace', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Tasks', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Created after backup', exact: true })).toBeVisible();
});

test('task editor validates starts and keyboard-accessible details, without repetitive demo copy', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('SAMPLE CALENDAR', { exact: true })).toBeVisible();
  await expect(page.locator('main')).not.toContainText(/a little|synthetic|fictional attendees|demo reminder/i);
  await page.getByRole('button', { name: 'Tasks', exact: true }).click();
  await page.getByRole('button', { name: 'New task', exact: true }).click();
  const editor = page.getByRole('dialog');
  await editor.getByLabel('Task title').fill('Check dates');
  await editor.getByLabel('Due date', { exact: true }).fill('2026-10-26');
  await editor.getByLabel('Start date', { exact: true }).fill('2026-10-27');
  await editor.getByRole('button', { name: 'Add task', exact: true }).click();
  await expect(editor.getByRole('alert')).toContainText('start');
  await page.keyboard.press('Escape');
  await expect(editor).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'New task', exact: true })).toBeFocused();
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/tasks-390-light.png', fullPage: true });
});
